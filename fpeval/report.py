"""Collect eval/summary.json files into results/summary.{csv,md}."""
import json
from pathlib import Path

import pandas as pd

from .eval_config import REFERENCES, VARIANTS

ROOT = Path(__file__).resolve().parents[1]

# (column, header, format) for the markdown tables.
RULE_COLS = [
    ("n_samples", "N", "{:.0f}"), ("yield", "yield", "{:.2f}"), ("n_rooms", "rooms", "{:.1f}"),
    ("overlap_ratio", "overlap", "{:.3f}"), ("hole_ratio", "holes", "{:.3f}"),
    ("boundary_coverage", "bnd cov", "{:.3f}"), ("outside_boundary_ratio", "outside", "{:.3f}"),
    ("adj_components", "adj comp", "{:.2f}"), ("frac_nonrectilinear_rooms", "non-rect", "{:.3f}"),
    ("frac_area_violation", "area viol", "{:.3f}"), ("frac_width_violation", "width viol", "{:.3f}"),
    ("frac_aspect_violation", "aspect viol", "{:.3f}"), ("any_rule_violation", "any viol", "{:.2f}"),
]
PAIRED_COLS = [
    ("room_count_match", "count match", "{:.2f}"), ("type_multiset_match", "types match", "{:.2f}"),
    ("adjacency_f1", "adj F1", "{:.2f}"), ("type_miou", "type mIoU", "{:.2f}"),
    ("pixel_type_acc", "pixel acc", "{:.2f}"),
]
DIST_COLS = [
    ("fid", "FID", "{:.1f}"), ("kid_x1000", "KIDx1e3", "{:.1f}"),
    ("fid_vs_gt", "FID vs GT", "{:.1f}"), ("fid_gt_vs_ref", "FID GT floor", "{:.1f}"),
    ("dist_room_count_tv", "count TV", "{:.2f}"), ("dist_room_type_jsd", "type JSD", "{:.3f}"),
    ("dist_area_frac_w1", "area-frac W1", "{:.3f}"), ("dist_aspect_w1", "aspect W1", "{:.2f}"),
    ("dist_room_area_m2_w1", "room m2 W1", "{:.1f}"),
]


def _fmt(v, f):
    return "–" if v is None or pd.isna(v) else f.format(v)


def _table(df, cols, label_col):
    head = "| " + " | ".join([label_col] + [h for _, h, _ in cols]) + " |"
    sep = "|" + "---|" * (len(cols) + 1)
    rows = ["| " + " | ".join([str(idx)] + [_fmt(r.get(c), f) for c, _, f in cols]) + " |"
            for idx, r in df.iterrows()]
    return "\n".join([head, sep, *rows])


def write_report():
    var = {}
    for key in VARIANTS:
        p = ROOT / "outputs" / key / "eval" / "summary.json"
        if p.exists():
            var[key] = json.load(open(p))
    refs = {}
    for name, (d, split, *_) in REFERENCES.items():
        p = ROOT / d / "eval" / (split or "all") / "summary.json"
        if p.exists():
            refs[name] = json.load(open(p))
    vdf = pd.DataFrame.from_dict(var, orient="index")
    if "raster" in vdf:
        # Rectilinearity of approxPolyDP-vectorized rasters measures the converter, not the model.
        vdf.loc[vdf.raster.fillna(False).astype(bool), "frac_nonrectilinear_rooms"] = None
    if "n_gt_inputs" in vdf:
        # FID against a handful of GT plans is meaningless.
        vdf.loc[vdf.n_gt_inputs < 50, ["fid_vs_gt", "kid_vs_gt_x1000", "fid_gt_vs_ref"]] = None
    rdf = pd.DataFrame.from_dict(refs, orient="index")
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    vdf.to_csv(out / "summary_variants.csv")
    rdf.to_csv(out / "summary_references.csv")

    md = ["# Evaluation results", "",
          "Generated by `python -m fpeval.evaluate report`. Metric definitions: docs/metrics.md.", "",
          "## Ground-truth baselines (rule metrics on real plans)", "",
          _table(rdf, RULE_COLS, "reference"), ""]
    for ref in vdf["ref"].unique():
        sub = vdf[vdf.ref == ref].copy()
        sub.index = [f"{i} ({c})" for i, c in zip(sub.index, sub.condition)]
        md += [f"## Generated vs {ref}", "",
               "### Rules", "", _table(sub, RULE_COLS, "variant (condition)"), "",
               "### Paired with GT", "", _table(sub, PAIRED_COLS, "variant (condition)"), "",
               "### Distribution", "", _table(sub, DIST_COLS, "variant (condition)"), ""]
    (out / "summary.md").write_text("\n".join(md))
    print(f"wrote {out}/summary.md, summary_variants.csv, summary_references.csv")
