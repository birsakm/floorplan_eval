#!/usr/bin/env bash
# End-to-end DiffPlanner run (boundary-only condition, 'b' models): NodeDiff -> AdjacencyDiff ->
# PartitioningDiff -> post_processing (alignment, doors/windows) -> common format + renders.
# Usage: scripts/diffplanner/run.sh [ids_file] [variant] [batch_size]
set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT=$(pwd)
IDS=${1:-data/method_inputs/common_rplan_test/ids_test_all.txt}
VARIANT=${2:-rplan_boundary_test}
BS=${3:-1024}
OUT=$ROOT/outputs/diffplanner/$VARIANT
WORK=$OUT/raw/_work
SUB=$ROOT/external/methods/diffplanner
CK=$ROOT/checkpoints/diffplanner/trained_model
DJ=$ROOT/data/method_inputs/diffplanner/dataset/dataset_json/data_test.json
export CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-2}
export OMPI_MCA_btl=self,vader OMPI_MCA_pml=ob1
mkdir -p $OUT/raw
conda run -n fpe-diffplanner python scripts/diffplanner/prepare_work.py $DJ $IDS $WORK
N=$(conda run -n fpe-diffplanner python -c "import json;print(len(json.load(open('$WORK/dataset/dataset_json/data_test.json'))))")
COMMON="--dataset rplan --batch_size $BS --set_name test --num_samples $N --support_boundary True --support_partial False"
T0=$(date +%s)
(cd $WORK/node_diff/scripts && conda run --no-capture-output -n fpe-diffplanner python $SUB/node_diff/scripts/sample.py $COMMON \
   --model_path $CK/node_diff/scripts/trained_model/b_model300000.pt --support_conditions '')
(cd $WORK/adjacency_diff/scripts && conda run --no-capture-output -n fpe-diffplanner python $SUB/adjacency_diff/scripts/sample.py $COMMON \
   --model_path $CK/adjacency_diff/scripts/trained_model/bncsl_model300000.pt --support_conditions ncsl \
   --syn_dataset_path ../../output/output_json/b.json)
(cd $WORK/partitioning_diff/scripts && conda run --no-capture-output -n fpe-diffplanner python $SUB/partitioning_diff/scripts/sample.py $COMMON \
   --model_path $CK/partitioning_diff/scripts/trained_model/bncsla_model300000.pt --support_conditions ncsla \
   --syn_dataset_path ../../output/output_json/b.json)
cp $WORK/output/output_json/b.json $OUT/raw/b_raw.json
conda run --no-capture-output -n fpe-diffplanner python scripts/diffplanner/postprocess.py $OUT/raw/b_raw.json $OUT/raw/b_post.json
T1=$(date +%s)
rm -rf "${OUT:?}/samples" "${OUT:?}/gt_samples" "${OUT:?}/renders" "${OUT:?}/gt_renders"
PYTHONPATH=. conda run -n fpe python scripts/diffplanner/convert.py $OUT \
  --g2p_mat data/method_inputs/diffplanner/graph2plan_data/Network/data/data_test.mat
PYTHONPATH=. conda run -n fpe python -m fpeval.render $OUT
PYTHONPATH=. conda run -n fpe python scripts/common/render_gt.py $OUT
PYTHONPATH=. conda run -n fpe python scripts/common/write_run_info.py $OUT --method diffplanner \
  --submodule external/methods/diffplanner --checkpoint "checkpoints/diffplanner/trained_model/{node_diff/b,adjacency_diff/bncsl,partitioning_diff/bncsla}_model300000.pt" \
  --command "scripts/diffplanner/run.sh $IDS $VARIANT $BS" --conditioning "RPLAN boundary + entrance (Graph2Plan/DiffPlanner test split); bubble diagram generated by NodeDiff+AdjacencyDiff" \
  --ids $IDS --infer_seconds $((T1-T0)) --env fpe-diffplanner \
  --notes "torch 2.0.1+cu118 (orig 2.0.0); 1000-step DDPM per stage; one sample per boundary; vector output, aligned by the official post_processing.py"
